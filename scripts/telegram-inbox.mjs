/**
 * TODO 1.11 — Telegram paper inbox. Students DM a PDF to @Cse_hub_bot with a
 * short caption; this script (run by telegram-inbox.yml every 30 min) lands it
 * on the site:
 *
 *   1. poll getUpdates (offset persisted via the workflow's Actions cache)
 *   2. accept private-chat PDF documents only (photos/other docs get a reply)
 *   3. parse the caption: `sem3 os 2023` / `s4 dbms 2024 back`
 *      → semester, year, subjectId (validated against subject-index.json),
 *        kind (regular/back/special), session inferred from the semester parity
 *   4. download the file (≤ 8 MB, ADR-3) → public/papers/<year>/<id>.pdf
 *   5. append a `verified: false`, `source: 'contributed'` entry to
 *      src/data/papers/<year>.ts (creating the year file + index spread if new)
 *   6. reply to the sender with the result
 *
 * The maintainer flips `verified: true` after checking against the official
 * scheme (moderation ritual, TODO 6.3). Only the contributor's @username (or
 * first name) is stored — never phone numbers or anything else.
 *
 * NOTE: year files under src/data/papers are leaf modules (type-only imports),
 * so importing them here is Node-safe. The semester data files are NOT
 * importable (extensionless `./yt` import) — hence the textual subject index.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const token = process.env.TELEGRAM_BOT_TOKEN;
const OFFSET_FILE = join(root, 'scripts', '.tg-inbox-offset.json');
const MAX_BYTES = 8_000_000; // ADR-3 cap for repo-stored PDFs
const MAX_UPDATES_PER_RUN = 20;

if (!token) {
  console.log('[telegram-inbox] TELEGRAM_BOT_TOKEN not set — skipping.');
  process.exit(0);
}

const api = async (method, body) => {
  const res = await fetch(`https://api.telegram.org/bot${token}/${method}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body ?? {}),
  });
  const data = await res.json();
  if (!data.ok) throw new Error(`${method} failed: ${data.description}`);
  return data.result;
};

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const reply = (chatId, text) => api('sendMessage', { chat_id: chatId, text, parse_mode: 'HTML', disable_web_page_preview: true });

/* ── subject index (generated by build-subject-index.mjs in the same job) ── */
const subjectIndex = JSON.parse(
  readFileSync(join(root, 'scripts', 'generated', 'subject-index.json'), 'utf8'),
);

/* ── caption parsing ─────────────────────────────────────────────────────── */

function parseCaption(raw) {
  const caption = String(raw ?? '');
  const lower = caption.toLowerCase();
  const tokens = lower.match(/[a-z0-9.]+/g) ?? [];

  const yearMatch = lower.match(/\b(20[12]\d)\b/);
  const semMatch = lower.match(/\b(?:sem)?\s*s\s*([1-6])\b/) ?? lower.match(/\bsem\s*([1-6])\b/);
  const kind = /\bspecial\b/.test(lower) ? 'special' : /\bback\b/.test(lower) ? 'back' : 'regular';

  if (!yearMatch || !semMatch) return { error: 'missing year/semester' };
  const year = Number(yearMatch[1]);
  const semester = Number(semMatch[1]);
  const skip = new Set([yearMatch[1], semMatch[0].replace(/[^a-z0-9]/g, ''), 'sem', 's', 'back', 'special', 'paper', 'pyq']);

  const candidates = tokens.filter((t) => !skip.has(t));
  const pool = subjectIndex.filter((s) => s.semester === semester);
  const subject = candidates
    .map((t) =>
      pool.find((s) => s.id === t || s.code === t) ??
      pool.find((s) => t.length >= 3 && s.shortName.toLowerCase().startsWith(t)),
    )
    .find(Boolean);

  if (!subject) return { error: 'unknown subject', semester, year };
  return { year, semester, subjectId: subject.id, shortName: subject.shortName, kind };
}

const helpText = (ctx = '') =>
  `📄 <b>Paper upload format</b>\n\nSend the PDF with a caption like:\n<code>sem3 os 2023</code>\n<code>s4 dbms 2024 back</code>\n\n• <b>semester</b> — sem3 … sem6 (or s3)\n• <b>subject</b> — short code (os, dbms, cn, web…)\n• <b>year</b> — exam year (2023/2024…)\n• optional: <code>back</code> for back papers\n\nPDF only for now 🙏 — photos are not accepted yet; scan with CamScanner or Microsoft Lens.${ctx ? `\n\n⚠️ ${ctx}` : ''}`;

/* ── year-file plumbing ──────────────────────────────────────────────────── */

const entryTs = (p) => `  {
    id: '${p.id}',
    year: ${p.year},
    session: '${p.session}',
    semester: ${p.semester},
    subjectId: '${p.subjectId}',
    kind: '${p.kind}',
    fileUrl: '${p.fileUrl}',
    sizeKb: ${p.sizeKb},
    source: 'contributed',
    contributedBy: '${p.contributedBy}',
    verified: false, // pending maintainer check against the official scheme (TODO 6.3)
  },
`;

const sanitizeHandle = (from) => {
  if (from?.username && /^[A-Za-z0-9_]+$/.test(from.username)) return `@${from.username}`;
  const name = String(from?.first_name ?? '').replace(/['\\\r\n]/g, '');
  return name || 'telegram-user';
};

function appendPaper(year, entry) {
  const yearFile = join(root, 'src', 'data', 'papers', `${year}.ts`);
  if (!existsSync(yearFile)) {
    writeFileSync(
      yearFile,
      `import type { Paper } from '../../types';

/**
 * BTEUP previous-year question papers — ${year}.
 * Bot-contributed entries land here unverified (TODO 1.11); the maintainer
 * flips \`verified: true\` after checking each against the official scheme.
 */
export const PAPERS_${year}: Paper[] = [
${entryTs(entry)}];
`,
    );
    // Add the new year to the index spread (sorted newest first).
    const indexPath = join(root, 'src', 'data', 'papers', 'index.ts');
    const indexSrc = readFileSync(indexPath, 'utf8');
    const years = [...indexSrc.matchAll(/PAPERS_(\d{4})/g)]
      .map((m) => Number(m[1]))
      .filter((y, i, a) => a.indexOf(y) === i);
    if (!years.includes(year)) years.push(year);
    years.sort((a, b) => b - a);
    const spread = years.map((y) => `...PAPERS_${y}`).join(', ');
    writeFileSync(
      indexPath,
      indexSrc.replace(
        /export const PAPERS: Paper\[\] = \[[^\]]*\];/,
        `export const PAPERS: Paper[] = [${spread}];`,
      ),
    );
    console.log(`[telegram-inbox] created year file for ${year} (+ index spread)`);
    return;
  }
  const src = readFileSync(yearFile, 'utf8');
  const at = src.lastIndexOf('];');
  if (at === -1) throw new Error(`unexpected format in ${year}.ts`);
  writeFileSync(yearFile, src.slice(0, at) + entryTs(entry) + src.slice(at));
}

const yearHasId = (year, id) => {
  const yearFile = join(root, 'src', 'data', 'papers', `${year}.ts`);
  return existsSync(yearFile) && readFileSync(yearFile, 'utf8').includes(`id: '${id}'`);
};

/* ── process one document ────────────────────────────────────────────────── */

async function handleDocument(msg, doc) {
  const chatId = msg.chat.id;
  const isPdf = doc.mime_type === 'application/pdf' || String(doc.file_name ?? '').toLowerCase().endsWith('.pdf');
  if (!isPdf) return reply(chatId, helpText('Only PDF documents are accepted for now.'));
  if ((doc.file_size ?? 0) > MAX_BYTES)
    return reply(chatId, helpText('That PDF is over the 8 MB limit. Re-scan at a lower DPI — question papers compress well.'));

  const parsed = parseCaption(msg.caption);
  if (parsed.error) {
    const hint = parsed.error === 'unknown subject'
      ? `No subject matching your caption in semester ${parsed.semester}. Use the short code, e.g. <code>sem3 os 2023</code>.`
      : '';
    return reply(chatId, helpText(hint));
  }

  const session = parsed.semester % 2 === 1 ? 'odd' : 'even';
  const id = `${parsed.year}-${session}-s${parsed.semester}-${parsed.subjectId}${parsed.kind === 'regular' ? '' : `-${parsed.kind}`}`;
  if (yearHasId(parsed.year, id)) return reply(chatId, `✅ Already on the hub: <code>${id}</code> — thanks anyway! 🙏`);

  const file = await api('getFile', { file_id: doc.file_id });
  const res = await fetch(`https://api.telegram.org/file/bot${token}/${file.file_path}`);
  if (!res.ok) throw new Error(`file download failed: ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  if (bytes.length > MAX_BYTES) return reply(chatId, helpText('That PDF is over the 8 MB limit.'));

  const dir = join(root, 'public', 'papers', String(parsed.year));
  mkdirSync(dir, { recursive: true });
  const pdfPath = join(dir, `${id}.pdf`);
  writeFileSync(pdfPath, bytes);

  const entry = {
    id,
    year: parsed.year,
    session,
    semester: parsed.semester,
    subjectId: parsed.subjectId,
    kind: parsed.kind,
    fileUrl: `/papers/${parsed.year}/${id}.pdf`,
    sizeKb: Math.round(bytes.length / 1024),
    contributedBy: sanitizeHandle(msg.from),
  };
  appendPaper(parsed.year, entry);
  console.log(`[telegram-inbox] landed ${id} (${entry.sizeKb} kB, ${bytes.length} bytes) — unverified`);

  return reply(
    chatId,
    `🎉 <b>Received!</b>\n<code>${id}</code> (${entry.sizeKb} kB) is queued for the hub — it goes live once reviewed. Thank you! 🙏\n\n🔗 https://2nd-year-lateral.vercel.app/papers`,
  );
}

/* ── poll loop ───────────────────────────────────────────────────────────── */

let offset = 0;
if (existsSync(OFFSET_FILE)) {
  try {
    offset = JSON.parse(readFileSync(OFFSET_FILE, 'utf8')).offset ?? 0;
  } catch {
    /* corrupt cache file — start fresh */
  }
}

const updates = await api('getUpdates', { offset, timeout: 0, allowed_updates: ['message'] });
if (updates.length === 0) {
  console.log('[telegram-inbox] no pending messages.');
  process.exit(0);
}

let landed = 0;
let maxUpdateId = offset - 1;
for (const update of updates.slice(0, MAX_UPDATES_PER_RUN)) {
  maxUpdateId = Math.max(maxUpdateId, update.update_id);
  const msg = update.message;
  if (!msg || msg.chat.type !== 'private') continue;

  try {
    if (msg.document) {
      await handleDocument(msg, msg.document);
      landed += 1;
    } else if (msg.photo || (msg.text && !msg.text.startsWith('/'))) {
      await reply(msg.chat.id, helpText());
    }
    // /start, /help and other bot commands: silent ignore (BotFather handles
    // the /start greeting; anything else gets the format reply above).
  } catch (err) {
    console.error(`[telegram-inbox] update ${update.update_id} failed: ${err.message}`);
    await reply(msg.chat.id, '😔 Something went wrong processing that file — please try again.').catch(() => {});
  }
}

writeFileSync(OFFSET_FILE, `${JSON.stringify({ offset: maxUpdateId + 1, updated: new Date().toISOString() }, null, 2)}\n`);
console.log(`[telegram-inbox] processed ${updates.length} updates, ${landed} paper(s) landed, offset → ${maxUpdateId + 1}`);
