let noteCounter = 0;

/** Builds a StudyNote. Never fabricates URLs — only stable, known references. */
export function n(
  title: string,
  format: StudyNote['format'],
  description: string,
  href: string,
  source: StudyNote['source'] = 'supplementary',
): StudyNote {
  noteCounter += 1;
  return { id: `note-${noteCounter}`, title, source, format, description, href };
}

